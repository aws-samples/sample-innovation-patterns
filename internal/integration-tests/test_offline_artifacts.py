"""Offline tests for the ``scripts/*.mk`` parsers, against fixture Makefiles.

This module is why ``artifacts.py`` is a separate module rather than folded into
``test_compose.py``: the composition assertions are only testable offline if their
parsers can be pointed at a fixture.

Each fixture includes a NEGATIVE case, so a parser is shown to *detect* the defect
rather than merely to pass on a healthy input. A parser that returned ``True`` for
everything would pass a positive-only suite.
"""

from __future__ import annotations

from pathlib import Path

import pytest

import artifacts

GOOD_DEPLOY_MK = """\
# Generated by /ipa-compose
# stacks: frontend backend queue
# engine: cloudformation

.PHONY: deploy teardown deploy-frontend deploy-backend deploy-queue

deploy: deploy-queue deploy-backend deploy-frontend

teardown: teardown-frontend teardown-backend teardown-queue

deploy-queue:
\taws cloudformation deploy --stack-name $(NS)-$(ENV)-queue \\
\t\t--parameter-overrides Namespace=$(NS) Environment=$(ENV)

deploy-backend:
\taws cloudformation deploy --stack-name $(NS)-$(ENV)-backend \\
\t\t--parameter-overrides Namespace=$(NS) EnableSqsIntegration=true \\
\t\t\tSqsQueueUrl=$(QUEUE_URL)

deploy-frontend:
\taws cloudformation deploy --stack-name $(NS)-$(ENV)-frontend
"""

BAD_ORDER_DEPLOY_MK = """\
# stacks: frontend backend queue

deploy: deploy-queue deploy-backend deploy-frontend

teardown: teardown-queue teardown-backend teardown-frontend
"""

GOOD_BUILD_MK = """\
.PHONY: build build-web build-rest-lambda

build: build-web build-rest-lambda

build-web:
\tcd web-client && npm ci && npm run build

build-rest-lambda:
\tcd app-lib && docker build -t rest-lambda .
"""

BAD_BUILD_MK = """\
build-web:
\tcd frontend && npm ci && npm run build

build-rest-lambda:
\tdocker build -t a .

build-rest-lambda:
\tdocker build -t b .
"""

GOOD_ENV_MK = """\
.PHONY: update-env update-env-backend update-env-frontend

update-env: update-env-backend update-env-frontend

update-env-backend:
\t@echo API_URL=...

update-env-frontend:
\t@echo APP_URL=...
"""


# --------------------------------------------------------------------------- #
# Artifact presence
# --------------------------------------------------------------------------- #


def test_there_are_eight_expected_artifacts():
    assert len(artifacts.EXPECTED_ARTIFACTS) == 8


def test_missing_artifacts_names_every_absent_one(tmp_path: Path):
    (tmp_path / "scripts").mkdir()
    (tmp_path / "scripts" / "deploy.mk").write_text(GOOD_DEPLOY_MK)

    missing = artifacts.missing_artifacts(tmp_path)

    assert "scripts/deploy.mk" not in missing
    assert "scripts/env.mk" in missing
    assert len(missing) == 7


def test_missing_artifacts_is_empty_for_a_complete_composition(tmp_path: Path):
    (tmp_path / "scripts").mkdir()
    for rel in artifacts.EXPECTED_ARTIFACTS:
        (tmp_path / rel).write_text("x\n")
    assert artifacts.missing_artifacts(tmp_path) == []


# --------------------------------------------------------------------------- #
# Targets and prerequisites
# --------------------------------------------------------------------------- #


def test_targets_excludes_phony_and_recipe_lines():
    found = artifacts.targets(GOOD_DEPLOY_MK)
    assert ".PHONY" not in found
    assert "deploy" in found and "deploy-backend" in found


def test_prerequisites_returns_them_in_order():
    assert artifacts.prerequisites(GOOD_DEPLOY_MK, "deploy") == [
        "deploy-queue", "deploy-backend", "deploy-frontend",
    ]


def test_prerequisites_of_an_absent_target_is_empty():
    assert artifacts.prerequisites(GOOD_DEPLOY_MK, "nope") == []


def test_target_count_detects_a_duplicate():
    """A duplicated container-build target either builds twice or builds the wrong
    one depending on ordering."""
    assert artifacts.target_count(GOOD_BUILD_MK, "build-rest-lambda") == 1
    assert artifacts.target_count(BAD_BUILD_MK, "build-rest-lambda") == 2


def test_target_body_captures_only_that_target_s_recipe():
    body = artifacts.target_body(GOOD_BUILD_MK, "build-web")
    assert "web-client" in body
    assert "docker build" not in body


# --------------------------------------------------------------------------- #
# Reverse ordering -- with a negative fixture
# --------------------------------------------------------------------------- #


def test_teardown_is_recognised_as_the_reverse_of_deploy():
    """The two prerequisite lists never share a name: MAKEFILE_TEMPLATES.md:54
    generates ``deploy-{suffix}`` and :162 generates ``teardown-{suffix}``. So the
    comparison is on tier suffixes, and comparing raw names would report every
    healthy artifact as misordered.
    """
    ok, dep, tear = artifacts.teardown_is_reverse_of_deploy(GOOD_DEPLOY_MK)
    assert ok
    assert artifacts._suffixes(tear, "teardown-") == list(
        reversed(artifacts._suffixes(dep, "deploy-"))
    )
    assert tear != list(reversed(dep)), "raw names must NOT be expected to match"


def test_a_teardown_in_the_same_order_as_deploy_is_detected():
    """The parser must DETECT the defect, not merely pass on a healthy input."""
    ok, dep, tear = artifacts.teardown_is_reverse_of_deploy(BAD_ORDER_DEPLOY_MK)
    assert ok is False
    assert dep and tear


def test_a_missing_deploy_target_is_not_reported_as_correctly_reversed():
    ok, _, _ = artifacts.teardown_is_reverse_of_deploy("teardown:\n\t@true\n")
    assert ok is False


# --------------------------------------------------------------------------- #
# Parameter overrides -- the only proof the cross-tier wiring fired
# --------------------------------------------------------------------------- #


def test_parameter_overrides_finds_the_sqs_integration_flag():
    params = artifacts.parameter_overrides(GOOD_DEPLOY_MK, "deploy-backend")
    assert params.get("EnableSqsIntegration") == "true"


def test_parameter_overrides_absent_flag_is_detected():
    params = artifacts.parameter_overrides(GOOD_DEPLOY_MK, "deploy-queue")
    assert "EnableSqsIntegration" not in params


def test_parameter_overrides_of_a_target_without_any_is_empty():
    assert artifacts.parameter_overrides(GOOD_BUILD_MK, "build-web") == {}


# --------------------------------------------------------------------------- #
# The header tier set
# --------------------------------------------------------------------------- #


def test_header_tiers_reads_the_generated_header():
    assert artifacts.header_tiers(GOOD_DEPLOY_MK) == {"frontend", "backend", "queue"}


def test_header_tiers_falls_back_to_deploy_targets_when_no_header_line():
    """A header-format change must degrade to a weaker check, never to a false pass."""
    no_header = GOOD_DEPLOY_MK.split("\n", 4)[4]
    assert artifacts.header_tiers(no_header) == {"frontend", "backend", "queue"}


# --------------------------------------------------------------------------- #
# The build and env artifacts, with negative fixtures
# --------------------------------------------------------------------------- #


def test_build_mk_frontend_directory_defect_is_detectable():
    """The template may emit ``cd frontend``, which does not exist in this
    repository -- failing twenty minutes into a build with an error about a missing
    directory."""
    assert "cd web-client" in GOOD_BUILD_MK
    assert "cd web-client" not in BAD_BUILD_MK
    assert "cd frontend" in BAD_BUILD_MK


@pytest.mark.parametrize("target", ["update-env-backend", "update-env-frontend"])
def test_env_mk_sync_targets_are_detectable(target: str):
    """Their absence is fully silent: the deployment succeeds and the frontend is
    served a config naming no API and no identity provider."""
    assert target in artifacts.targets(GOOD_ENV_MK)
    assert target not in artifacts.targets(GOOD_BUILD_MK)
